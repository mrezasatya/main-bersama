const rng = seeded(11);
const AGES = { ABC: ['A', 'B', 'C'], BC: ['B', 'C'], C: ['C'] } as const;

const items = ROWS.map(
  ([key, name, origin, timbre, layout, scale, base, count, color, age, diff]) => {
    const melody = Array.from({ length: 4 }, () => Math.floor(rng() * Math.min(count, 5)));
    // Hindari melodi yang semua nadanya sama bila alat musiknya punya lebih dari satu nada.
    if (count > 1 && melody.every((m) => m === melody[0]))
      melody[1] = (melody[0]! + 1) % Math.min(count, 5);
    return {
      id: key,
      ageGroup: AGES[age],
      difficulty: diff,
      speak: `Ayo main ${name}!`,
      label: cap(name),
      data: { nama: name, timbre, layout, scale, base, count, color, melody, speakAlso: [origin] },
      tags: ['musik', timbre, layout],
      review: 'perlu-ditinjau',
    };
  },
);

await writeContent('nada-nusantara', items);
